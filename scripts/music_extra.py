"""Extra (custom) background-music track for scripts/make_music.py, configured in sprites/music.json.

sprites/music.json:
  { "tracks": { "connect": { "file": "sprites/music/connect.txt" } },
    "play":   { "floor1": "connect", "floor2": "default", "floor3": "default", "escape": "default", "win": "default", "gameover": "default" } }

* The music ROM has ONE custom slot (track 6). The track text is "NOTE:frames NOTE:frames R:frames ..." (R = rest, frames of 1/60 s, 1..255, at most 127 entries);
  scripts/audio_to_music.py writes this format from an audio file. Lines starting with # are ignored.
* "play" says which track plays where; "default" = the built-in track (floors 1-3 tracks 0-2, escape 3, win 4, game over 5). A custom track loops
  (so use it for floors / escape, not for the win or game over jingle unless you want it to loop).
* Rule 1: a missing or invalid custom file never breaks the build: that track is dropped, the default music plays, and a warning is printed.
Output: the 128 entries of track 6 and rtl/bgm_cfg.vh (which track plays where).
"""
import json
import os

NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}
PLACES = ["floor1", "floor2", "floor3", "escape", "win", "gameover"]
DEFAULT_IDS = {"floor1": 0, "floor2": 1, "floor3": 2, "escape": 3, "win": 4, "gameover": 5}
CUSTOM_ID = 6
MAX_ENTRIES = 127


def hp(note):
    """half-period of the square wave at 100 MHz (same formula as make_music.py); 0 = rest"""
    if note == 'R':
        return 0
    n, o = (note[:-1], int(note[-1]))
    semis = NAMES[n] + 12 * (o - 4) - 9
    f = 440.0 * 2 ** (semis / 12.0)
    v = round(1e8 / (2 * f))
    if not 0 < v < (1 << 18):
        raise ValueError(f"note {note} is outside the range of the hardware (190 Hz and up)")
    return v


def parse_track_text(text):
    """-> [(frames, hp)] ; raises ValueError with a clear message"""
    toks = []
    for ln in text.splitlines():
        if ln.strip().startswith("#"):
            continue
        toks += ln.split()
    if not toks:
        raise ValueError("no notes")
    if len(toks) > MAX_ENTRIES:
        raise ValueError(f"{len(toks)} entries, the ROM holds {MAX_ENTRIES} per track")
    out = []
    for t in toks:
        if ":" not in t:
            raise ValueError(f"bad entry {t!r} (use NOTE:frames, e.g. C5:20 or R:10)")
        n, d = t.split(":", 1)
        if not d.isdigit() or not 1 <= int(d) <= 255:
            raise ValueError(f"bad length in {t!r} (1..255 frames)")
        try:
            out.append((int(d), hp(n)))
        except (KeyError, ValueError, IndexError) as e:
            raise ValueError(f"bad note in {t!r}: {e}")
    return out


def load(root):
    """-> dict(entries=[(frames,hp)] | None, ids={place: track id}, warnings=[...]); raises ValueError for a broken music.json"""
    path = os.path.join(root, "sprites", "music.json")
    res = {"entries": None, "ids": dict(DEFAULT_IDS), "warnings": [], "name": None}
    if not os.path.isfile(path):
        return res
    try:
        with open(path, encoding="utf-8") as f:
            cfg = json.load(f)
    except (OSError, ValueError) as e:
        raise ValueError(f"cannot read {path}: {e}")
    tracks = {k: v for k, v in cfg.get("tracks", {}).items() if not k.startswith("_")}
    if len(tracks) > 1:
        raise ValueError("only ONE custom track fits the music ROM (track 6)")
    play = {k: v for k, v in cfg.get("play", {}).items() if not k.startswith("_")}
    for k, v in play.items():
        if k not in PLACES:
            raise ValueError(f'play."{k}": unknown place (valid: {", ".join(PLACES)})')
        if v != "default" and v not in tracks:
            raise ValueError(f'play."{k}" = "{v}": no such track in "tracks"')
    if tracks:
        name, spec = next(iter(tracks.items()))
        if not isinstance(spec, dict) or not isinstance(spec.get("file"), str):
            raise ValueError(f'tracks."{name}" must be {{"file": "sprites/music/x.txt"}}')
        fpath = os.path.join(root, spec["file"])
        try:
            with open(fpath, encoding="utf-8") as f:
                res["entries"] = parse_track_text(f.read())
            res["name"] = name
        except OSError:
            res["warnings"].append(f'custom track "{name}": file missing ({spec["file"]}) -> default music plays')
        except ValueError as e:
            res["warnings"].append(f'custom track "{name}": {spec["file"]} is not valid ({e}) -> default music plays')
    for k, v in play.items():
        if v != "default":
            if res["entries"] is not None:
                res["ids"][k] = CUSTOM_ID
    return res


def bgm_vh(ids):
    return "\n".join([
        "// GENERATED by scripts/make_music.py from sprites/music.json - do not edit by hand.",
        "// Which music track plays where (0-2 floors, 3 escape, 4 win jingle, 5 game over jingle, 6 custom track).",
        "localparam [2:0] BGM_F1   = 3'd%d;" % ids["floor1"],
        "localparam [2:0] BGM_F2   = 3'd%d;" % ids["floor2"],
        "localparam [2:0] BGM_F3   = 3'd%d;" % ids["floor3"],
        "localparam [2:0] BGM_ESC  = 3'd%d;" % ids["escape"],
        "localparam [2:0] BGM_WIN  = 3'd%d;" % ids["win"],
        "localparam [2:0] BGM_OVER = 3'd%d;" % ids["gameover"],
        ""])


def write_text_if_changed(path, text):
    try:
        with open(path, "r", encoding="utf-8", newline="") as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    return True
