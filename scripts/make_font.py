#!/usr/bin/env python3
"""ฟอนต์ 8x8 1 bit + ข้อความบนจอ (P5) — วาดเองในสคริปต์ ไม่ใช้ไฟล์ฟอนต์ภายนอก

mem/font.mem  : 64 ตัว x 8 แถว = 512 บรรทัด, ค่า 2 hex ต่อแถว (bit 7 = คอลัมน์ซ้ายสุด), address = code*8 + row
mem/text.mem  : รหัสตัวอักษรของทุกข้อความต่อกัน (2 hex ต่อตัว)
rtl/text_layout.vh : ตำแหน่ง/ขนาด/ที่อยู่ของข้อความแต่ละบรรทัด (include ใน renderer.v)

รหัสตัวอักษร: 0-9 ตัวเลข, 10-35 A-Z, 36 ช่องว่าง, 37 '-', 38 ':', 39 '!', 40 '.'
             59-63 = ตัวเลขสด: 59 ชั้น (1-3), 60-63 = เวลา m m s s
ชื่อเกม: แก้ GAME_NAME ด้านล่างที่เดียว แล้วรันสคริปต์ใหม่

รัน: python3 scripts/make_font.py
"""
import os

GAME_NAME = 'DUNGEON'          # ชื่อเกม (ชั่วคราว) — เปลี่ยนที่นี่ที่เดียว (A-Z 0-9 ช่องว่าง, ไม่เกิน 18 ตัว)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ---------- glyph 5x7 (วางที่คอลัมน์ 1-5 แถว 0-6 ของช่อง 8x8) ----------
G = {
    '0': ['01110', '10001', '10011', '10101', '11001', '10001', '01110'],
    '1': ['00100', '01100', '00100', '00100', '00100', '00100', '01110'],
    '2': ['01110', '10001', '00001', '00010', '00100', '01000', '11111'],
    '3': ['11110', '00001', '00001', '01110', '00001', '00001', '11110'],
    '4': ['00010', '00110', '01010', '10010', '11111', '00010', '00010'],
    '5': ['11111', '10000', '11110', '00001', '00001', '10001', '01110'],
    '6': ['00110', '01000', '10000', '11110', '10001', '10001', '01110'],
    '7': ['11111', '00001', '00010', '00100', '01000', '01000', '01000'],
    '8': ['01110', '10001', '10001', '01110', '10001', '10001', '01110'],
    '9': ['01110', '10001', '10001', '01111', '00001', '00010', '01100'],
    'A': ['01110', '10001', '10001', '11111', '10001', '10001', '10001'],
    'B': ['11110', '10001', '10001', '11110', '10001', '10001', '11110'],
    'C': ['01110', '10001', '10000', '10000', '10000', '10001', '01110'],
    'D': ['11100', '10010', '10001', '10001', '10001', '10010', '11100'],
    'E': ['11111', '10000', '10000', '11110', '10000', '10000', '11111'],
    'F': ['11111', '10000', '10000', '11110', '10000', '10000', '10000'],
    'G': ['01110', '10001', '10000', '10111', '10001', '10001', '01111'],
    'H': ['10001', '10001', '10001', '11111', '10001', '10001', '10001'],
    'I': ['01110', '00100', '00100', '00100', '00100', '00100', '01110'],
    'J': ['00111', '00010', '00010', '00010', '00010', '10010', '01100'],
    'K': ['10001', '10010', '10100', '11000', '10100', '10010', '10001'],
    'L': ['10000', '10000', '10000', '10000', '10000', '10000', '11111'],
    'M': ['10001', '11011', '10101', '10101', '10001', '10001', '10001'],
    'N': ['10001', '10001', '11001', '10101', '10011', '10001', '10001'],
    'O': ['01110', '10001', '10001', '10001', '10001', '10001', '01110'],
    'P': ['11110', '10001', '10001', '11110', '10000', '10000', '10000'],
    'Q': ['01110', '10001', '10001', '10001', '10101', '10010', '01101'],
    'R': ['11110', '10001', '10001', '11110', '10100', '10010', '10001'],
    'S': ['01111', '10000', '10000', '01110', '00001', '00001', '11110'],
    'T': ['11111', '00100', '00100', '00100', '00100', '00100', '00100'],
    'U': ['10001', '10001', '10001', '10001', '10001', '10001', '01110'],
    'V': ['10001', '10001', '10001', '10001', '10001', '01010', '00100'],
    'W': ['10001', '10001', '10001', '10101', '10101', '10101', '01010'],
    'X': ['10001', '10001', '01010', '00100', '01010', '10001', '10001'],
    'Y': ['10001', '10001', '01010', '00100', '00100', '00100', '00100'],
    'Z': ['11111', '00001', '00010', '00100', '01000', '10000', '11111'],
    ' ': ['00000'] * 7,
    '-': ['00000', '00000', '00000', '11111', '00000', '00000', '00000'],
    ':': ['00000', '01100', '01100', '00000', '01100', '01100', '00000'],
    '!': ['00100', '00100', '00100', '00100', '00100', '00000', '00100'],
    '.': ['00000', '00000', '00000', '00000', '00000', '01100', '01100'],
}
CODE = {c: i for i, c in enumerate('0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ')}
CODE.update({' ': 36, '-': 37, ':': 38, '!': 39, '.': 40})
LIVE = {'{F}': 59, '{M1}': 60, '{M0}': 61, '{S1}': 62, '{S0}': 63}

font = [[0] * 8 for _ in range(64)]
for ch, rows in G.items():
    for r, bits in enumerate(rows):
        font[CODE[ch]][r] = int(bits, 2) << 2      # 5 bit ชิดคอลัมน์ 1-5 ของ 8
# รหัสสด 59-63: ให้ glyph ว่าง (renderer แทนด้วยตัวเลขจริง)


def encode(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == '{':
            j = s.index('}', i) + 1
            out.append(LIVE[s[i:j]]); i = j
        else:
            out.append(CODE[s[i]]); i += 1
    return out


# ---------- ข้อความต่อหน้าจอ: (หน้าจอ, บรรทัด, ข้อความ, scale, y, กะพริบ) ----------
# หน้าจอข้อความ: 1 TITLE, 2 FLOOR CLEAR, 3 ESCAPE banner, 4 WIN, 5 GAME OVER (บรรทัดละไม่เกิน 2)
assert len(GAME_NAME) <= 18 and all(c in CODE for c in GAME_NAME)
LINES = [
    (1, 0, GAME_NAME,        4,  96, 0),
    (1, 1, 'PRESS BTNC',     2, 360, 1),
    (2, 0, 'FLOOR {F} CLEAR', 4, 176, 0),
    (3, 0, 'ESCAPE!',        4,  40, 0),
    (4, 0, 'YOU WIN',        4, 160, 0),
    (4, 1, '{M1}{M0}:{S1}{S0}', 4, 260, 0),
    (5, 0, 'GAME OVER',      4, 160, 0),
    (5, 1, 'PRESS BTNC',     2, 300, 1),
]
text = []
desc = {}
for scr, ln, s, sc, y, bl in LINES:
    codes = encode(s)
    w = len(codes) * 8 * sc
    x = (640 - w) // 2
    desc[(scr, ln)] = (y, x, w, 8 * sc, 1 if sc == 4 else 0, len(text), bl)
    text += codes
assert len(text) <= 128

with open(os.path.join(ROOT, 'mem', 'font.mem'), 'w') as f:
    f.write('\n'.join(f'{v:02x}' for g in font for v in g) + '\n')
with open(os.path.join(ROOT, 'mem', 'text.mem'), 'w') as f:
    f.write('\n'.join(f'{v:02x}' for v in text + [36] * (128 - len(text))) + '\n')

vh = ['// สร้างโดย scripts/make_font.py — อย่าแก้มือ (ชื่อเกมแก้ที่ GAME_NAME ในสคริปต์)',
      '// บรรทัดข้อความ: หน้าจอ s (1..5) บรรทัด l (0..1): Y, X, W(px), H(px), S (0 = 2x, 1 = 4x), B (ที่อยู่ใน text.mem), K (กะพริบ)']
for scr in range(1, 6):
    for ln in range(2):
        y, x, w, h, s4, b, bl = desc.get((scr, ln), (0, 0, 0, 0, 0, 0, 0))
        vh.append(f'localparam [9:0] T{scr}{ln}_Y = 10\'d{y}, T{scr}{ln}_X = 10\'d{x}, T{scr}{ln}_W = 10\'d{w}, '
                  f'T{scr}{ln}_H = 10\'d{h}; localparam T{scr}{ln}_S = {s4}, T{scr}{ln}_B = {b}, T{scr}{ln}_K = {bl};')
with open(os.path.join(ROOT, 'rtl', 'text_layout.vh'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(vh) + '\n')

# preview
try:
    from PIL import Image
    im = Image.new('RGB', (16 * 9 * 4, 4 * 9 * 4), (30, 30, 50))
    for c in range(64):
        for r in range(8):
            for b in range(8):
                if font[c][r] >> (7 - b) & 1:
                    for dy in range(4):
                        for dx in range(4):
                            im.putpixel(((c % 16) * 36 + b * 4 + dx, (c // 16) * 36 + r * 4 + dy), (255, 255, 255))
    im.save(os.path.join(ROOT, 'docs', 'font_preview.png'))
except ImportError:
    pass
print(f'font: {len(G)} glyphs, text: {len(text)} chars in {len(LINES)} lines')
