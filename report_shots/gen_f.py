from tl import TL
# ---- F: floor 2 form 3 (SW1 + SW3 x2, DEBUG) -> shoot turrets in C1 (fig 23) -> boss 2 (fig 32). SW0 (DEBUG) holds the boss door open
t = TL().intro()
t.lines.append("0:150:6000")
t.at(160); t.pulse2('1')
t.at(460); t.pulse2('3')
t.at(720); t.pulse2('3')
t.at(850); t.hold('R', 106)                     # START -> C1
t.at(1270)                                      # lock + box dialogs over
t.hold('U', 65); t.hold('R', 40); t.wait(5)
for _ in range(10): t.hold('C', 3); t.wait(10)  # shoot (form 3)
t.wait(20); t.spam('2', 8, 30)
t.hold('R', 135); t.hold('D', 62); t.hold('R', 40)   # -> right door (boss door L) -> boss room 2
t.wait(320)
for _ in range(60): t.hold('C', 3); t.wait(12)
t.save('F.txt', 'job F: floor 2 boss, form 3 (gen_f.py)')
